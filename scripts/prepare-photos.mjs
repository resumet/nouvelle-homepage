import { readFile, writeFile, mkdir, stat } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import sharp from 'sharp';

// Deterministic resizing/compression only. Originals and the photographed spaces stay unchanged.
const selections = JSON.parse(await readFile('scripts/photo-selections.json', 'utf8'));
await mkdir('public/images/hotel', { recursive: true });
const images = {};
const provenance = [];
let originalBytes = 0, outputBytes = 0;
for (const { key, source, alt, roomType, bookingPhotoId } of selections) {
  const buffer = await readFile(source);
  const metadata = await sharp(buffer).metadata();
  const widths = [640, 960, 1280].filter(width => width <= metadata.width);
  if (!widths.includes(metadata.width) && metadata.width < 1280) widths.push(metadata.width);
  const stem = key.replace(/[A-Z]/g, letter => `-${letter.toLowerCase()}`);
  const variants = [];
  let last;
  for (const width of widths) {
    const src = `images/hotel/${stem}-${width}.webp`;
    last = await sharp(buffer).rotate().resize({ width, withoutEnlargement: true }).webp({ quality: 83, effort: 5 }).toFile(`public/${src}`);
    variants.push({ src, width: last.width });
    outputBytes += last.size;
  }
  images[key] = { src: variants.at(-1).src, alt, width: last.width, height: last.height, variants };
  originalBytes += buffer.length;
  provenance.push({ key, source, roomType, bookingPhotoId, sha256: createHash('sha256').update(buffer).digest('hex'), fullSizeWebp: variants.at(-1).src, originalBytes: buffer.length, fullSizeBytes: (await stat(`public/${variants.at(-1).src}`)).size });
}
await writeFile('src/data/photos.ts', `// Generated by npm run assets:photos from operator-provided hotel photographs.\nimport type { HotelImage } from './hotel';\n\nexport const photos = ${JSON.stringify(images, null, 2)} satisfies Record<string, HotelImage>;\n`);
await writeFile('docs/PHOTO_ASSETS.json', JSON.stringify({ source: 'Operator-provided photographs in the local photo folders', processing: 'Auto-orientation, downsampling and WebP encoding; no generated imagery or enlargement', images: provenance }, null, 2) + '\n');
console.log(JSON.stringify({ photographs: selections.length, webpFiles: selections.length * 3, originalBytes, totalResponsiveBytes: outputBytes, fullSizeBytes: provenance.reduce((sum, image) => sum + image.fullSizeBytes, 0) }));
