import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import sharp from 'sharp';

const selections = [
  { slug: 'gwangjang', title: 'Gwangjang Market, Seoul 02.jpg', alt: '음식 노점과 방문객이 있는 광장시장 내부', author: 'Bgag', license: 'CC0 1.0', licenseUrl: 'https://creativecommons.org/publicdomain/zero/1.0/' },
  { slug: 'ddp', title: 'Dongdaemun Design Plaza - DDP2376.jpg', alt: '저녁 조명이 켜진 동대문디자인플라자의 곡선 외관', author: 'lumoplank', license: 'CC0 1.0', licenseUrl: 'https://creativecommons.org/publicdomain/zero/1.0/' },
  { slug: 'jongmyo', title: 'Jongmyo Shrine 01.jpg', alt: '나무 사이로 보이는 종묘 입구의 전통 문', author: 'Bgag', license: 'CC0 1.0', licenseUrl: 'https://creativecommons.org/publicdomain/zero/1.0/' },
  { slug: 'changgyeonggung', title: 'Changgyeonggung, Seoul - Changgyeonggung2265.jpg', alt: '해 질 무렵 조명이 켜진 창경궁 명정전', author: 'lumoplank', license: 'CC0 1.0', licenseUrl: 'https://creativecommons.org/publicdomain/zero/1.0/' },
  { slug: 'insadong', title: 'Seoul-Insadong-06.jpg', alt: '인사동 상점의 외관', author: 'Tom@HK', license: 'CC BY 2.0', licenseUrl: 'https://creativecommons.org/licenses/by/2.0/' },
  { slug: 'cheonggyecheon', title: 'Cheonggyecheon, Seoul - Cheonggyecheon2321.jpg', alt: '돌다리와 산책로가 이어지는 청계천', author: 'lumoplank', license: 'CC0 1.0', licenseUrl: 'https://creativecommons.org/publicdomain/zero/1.0/' },
];
const cache = 'artifacts/attraction-sources';
await mkdir(cache, { recursive: true });
await mkdir('public/images/attractions', { recursive: true });
const headers = { 'User-Agent': 'NouverHotelWebsite/1.0 (photo preparation; https://github.com/resumet/nouvelle-homepage)' };
const get = async url => {
  const response = await fetch(url, { headers });
  if (!response.ok) throw new Error(`${response.status} ${url}`);
  return response;
};
const images = {}, credits = {}, sources = [];
for (const selection of selections) {
  const { slug, title, alt, author, license, licenseUrl } = selection;
  const sourceUrl = `https://commons.wikimedia.org/wiki/${encodeURIComponent(`File:${title.replaceAll(' ', '_')}`)}`;
  let info;
  try { info = JSON.parse(await readFile(`${cache}/${slug}.json`, 'utf8')); }
  catch {
    const query = new URLSearchParams({ action: 'query', titles: `File:${title}`, prop: 'imageinfo', iiprop: 'url|extmetadata', iiurlwidth: '1280', format: 'json' });
    const result = await (await get(`https://commons.wikimedia.org/w/api.php?${query}`)).json();
    info = Object.values(result.query.pages)[0].imageinfo[0];
    await writeFile(`${cache}/${slug}.json`, JSON.stringify(info, null, 2));
  }
  const actualLicense = info.extmetadata.LicenseShortName?.value;
  if (actualLicense !== license && !(license === 'CC0 1.0' && actualLicense === 'CC0')) throw new Error(`${slug}: expected ${license}, received ${actualLicense}`);
  let buffer;
  try { buffer = await readFile(`${cache}/${slug}.jpg`); }
  catch {
    buffer = Buffer.from(await (await get(info.thumburl)).arrayBuffer());
    await writeFile(`${cache}/${slug}.jpg`, buffer);
  }
  const variants = [];
  let last;
  for (const width of [640, 960, 1280]) {
    const src = `images/attractions/${slug}-${width}.webp`;
    last = await sharp(buffer).rotate().resize({ width, withoutEnlargement: true }).webp({ quality: 80, effort: 5 }).toFile(`public/${src}`);
    variants.push({ src, width: last.width });
  }
  images[slug] = { src: variants.at(-1).src, alt, width: last.width, height: last.height, variants };
  credits[slug] = { author, sourceUrl, license, licenseUrl };
  sources.push({ ...selection, sourceUrl, photographedAt: info.extmetadata.DateTimeOriginal?.value, originalUrl: info.url, downloadedUrl: info.thumburl, sha256: createHash('sha256').update(buffer).digest('hex'), verifiedLicense: actualLicense });
  console.log(`${slug}: ${actualLicense}, ${last.width} × ${last.height}`);
}
await writeFile('src/data/attraction-photos.ts', `// Generated by scripts/prepare-attractions.mjs from licensed Wikimedia Commons photographs.\nimport type { HotelImage } from './hotel';\nexport const attractionPhotos = ${JSON.stringify(images, null, 2)} satisfies Record<string, HotelImage>;\nexport const attractionCredits = ${JSON.stringify(credits, null, 2)};\n`);
await writeFile('docs/ATTRACTION_ASSETS.json', JSON.stringify({ processing: 'Downsampling and WebP encoding only; displayed with object-fit cover. Historical photographs, not live views. Separate from operator-provided hotel images.', sources }, null, 2) + '\n');
